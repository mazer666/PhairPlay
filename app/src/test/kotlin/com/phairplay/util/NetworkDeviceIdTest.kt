package com.phairplay.util

import android.content.Context
import android.content.SharedPreferences
import io.mockk.every
import io.mockk.mockk
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * NetworkDeviceIdTest — the device id that PhairPlay advertises.
 *
 * WHY this is a separate test class: the tests of `NetworkUtilsTest` mock
 * `ContentResolver`, whose class initializer calls into the platform (JNI) and
 * therefore cannot run on the host JVM — the whole file is excluded from the JVM
 * module. The device id has to be proven by a test that **actually runs**, so it
 * lives here.
 *
 * WHY the device id matters: it is the `deviceid` in the mDNS TXT record and the
 * `deviceID` in the RTSP answers. It identifies the installation to the sender.
 * The placeholder `aa:bb:cc:dd:ee:ff` that the code used before issue #23 was the
 * same on every television in the world, which let two receivers overwrite each
 * other in the pairing cache of the sender.
 */
class NetworkDeviceIdTest {

    private val mockContext: Context = mockk(relaxed = true)
    private val mockPrefs: SharedPreferences = mockk(relaxed = true)

    private fun prefsWith(stored: String?) {
        every { mockContext.getSharedPreferences("phairplay_prefs", Context.MODE_PRIVATE) } returns mockPrefs
        every { mockPrefs.getString("phairplay_device_mac", null) } returns stored
    }

    /**
     * Test: The generated device address has the shape of a MAC address.
     */
    @Test
    fun `generated device address has the mac address format`() {
        val mac = NetworkUtils.generateLocallyAdministeredMac()

        assertNotNull("MAC address should not be null", mac)
        assertTrue(
            "MAC address should match format xx:xx:xx:xx:xx:xx but was: $mac",
            mac.matches(Regex("[0-9a-f]{2}:[0-9a-f]{2}:[0-9a-f]{2}:[0-9a-f]{2}:[0-9a-f]{2}:[0-9a-f]{2}"))
        )
    }

    /**
     * Test: The generated address is marked as locally administered and unicast.
     *
     * WHY: the second-least-significant bit of the first octet marks the address as
     * locally administered — it was generated by software and can never be the
     * address of a real network card. The least-significant bit must be clear, so
     * that the address is not a multicast address.
     */
    @Test
    fun `generated device address is locally administered and unicast`() {
        repeat(20) {
            val first = NetworkUtils.generateLocallyAdministeredMac().take(2)
            val value = first.toInt(16)

            assertTrue(
                "The locally administered bit must be set, but the address started with $first",
                (value and 0x02) != 0
            )
            assertTrue(
                "The multicast bit must be clear, but the address started with $first",
                (value and 0x01) == 0
            )
        }
    }

    /**
     * Test: Two generated addresses are never the same.
     *
     * WHY: the address identifies the installation in the pairing cache of the
     * sender. Two installations must not claim the same device id — that was the
     * defect of the placeholder `aa:bb:cc:dd:ee:ff`, which every television used.
     */
    @Test
    fun `two generated addresses differ`() {
        val addresses = (1..50).map { NetworkUtils.generateLocallyAdministeredMac() }

        assertEquals(
            "Every generated address must be unique",
            addresses.size,
            addresses.toSet().size
        )
    }

    /**
     * Test: The advertised address is stable — the stored value is returned.
     *
     * WHY: the sender recognises the receiver across restarts by this value. A new
     * address on every start would make the pairing cache of the sender forget the
     * television again and again.
     */
    @Test
    fun `advertised address is taken from the storage`() {
        val stored = "aa:bb:cc:dd:ee:01"
        prefsWith(stored)

        val mac = NetworkUtils.getAdvertisedMac(mockContext)

        assertEquals(stored, mac)
    }
}
